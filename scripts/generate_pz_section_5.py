def _style_doc(doc: Document) -> None:
    style = doc.styles["Normal"]
    style.font.name = "Times New Roman"
    style.font.size = Pt(14)
    style._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    for section in doc.sections:
        section.top_margin = Pt(56.7)
        section.bottom_margin = Pt(56.7)
        section.left_margin = Pt(85.0)
        section.right_margin = Pt(42.5)


def main() -> None:
    OUT_DOCX.parent.mkdir(parents=True, exist_ok=True)
    doc = Document()
    _style_doc(doc)
    for para in TEXT:
        if para.startswith("5 Тестирование"):
            p = doc.add_paragraph(para)
            if p.runs:
                p.runs[0].bold = True
        elif para.startswith("Рисунок"):
            p = doc.add_paragraph(para)
            p.paragraph_format.space_before = Pt(12)
            p.paragraph_format.space_after = Pt(6)
            if p.runs:
                p.runs[0].italic = True
        elif para in ("Автоматическое тестирование", "Ручное тестирование"):
            p = doc.add_paragraph(para)
            if p.runs:
                p.runs[0].bold = True
        elif para == "":
            doc.add_paragraph("")
        else:
            doc.add_paragraph(para)
    doc.save(OUT_DOCX)
    OUT_TXT.write_text("\n".join(TEXT), encoding="utf-8")
    print(f"Wrote {OUT_DOCX}")
    print(f"Wrote {OUT_TXT}")


if __name__ == "__main__":
    main()
