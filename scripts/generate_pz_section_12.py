def _is_heading(line: str) -> bool:
    return line.startswith("1.2 ") or line.startswith("Модель ")


def _is_caption(line: str) -> bool:
    return line.startswith("Рисунок ")


def _is_formula_block(line: str) -> bool:
    s = line.strip()
    if not s:
        return False
    if s.startswith("state(") or s.startswith("bookable("):
        return True
    if s.startswith("p =") or s.startswith("level("):
        return True
    if s.startswith("ψ(") or s.startswith("N_") or s.startswith("N_free"):
        return True
    if s.endswith(")") and "(1." in s:
        return True
    if line.startswith("    "):
        return True
    return False


def build_docx() -> Document:
    doc = Document()
    style = doc.styles["Normal"]
    style.font.name = "Times New Roman"
    style._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    style.font.size = Pt(14)

    for line in SECTION_12_LINES:
        if not line.strip():
            doc.add_paragraph()
            continue

        if _is_heading(line):
            p = doc.add_paragraph(line)
            if p.runs:
                p.runs[0].bold = True
            continue

        if _is_caption(line):
            p = doc.add_paragraph(line)
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            if p.runs:
                p.runs[0].italic = True
            continue

        if _is_formula_block(line):
            p = doc.add_paragraph(line.strip())
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            for run in p.runs:
                run.font.name = "Cambria Math"
            continue

        if line.startswith("— "):
            doc.add_paragraph(line, style="List Bullet")
            continue

        doc.add_paragraph(line)

    return doc


def build_txt() -> str:
    return "\n".join(SECTION_12_LINES) + "\n"


def main() -> None:
    OUT_DOCX.parent.mkdir(parents=True, exist_ok=True)
    OUT_TXT.write_text(build_txt(), encoding="utf-8")
    build_docx().save(OUT_DOCX)
    print(f"OK: {OUT_DOCX}")
    print(f"OK: {OUT_TXT}")


if __name__ == "__main__":
    main()
