def _setup_doc() -> Document:
    doc = Document()
    style = doc.styles["Normal"]
    style.font.name = "Times New Roman"
    style._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    style.font.size = Pt(14)
    return doc


def _heading(doc: Document, text: str) -> None:
    p = doc.add_paragraph(text)
    if p.runs:
        p.runs[0].bold = True


def _para(doc: Document, text: str = "") -> None:
    if text.startswith("Рисунок "):
        p = doc.add_paragraph(text)
        p.runs[0].italic = True
        return
    doc.add_paragraph(text)


def _add_plan_table(doc: Document) -> None:
    headers = ["№ п/п", "Работы / этапы"] + WEEK_DATES
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    for i, h in enumerate(headers):
        t.rows[0].cells[i].text = h
        if t.rows[0].cells[i].paragraphs[0].runs:
            t.rows[0].cells[i].paragraphs[0].runs[0].bold = True
    for idx, (title, weeks) in enumerate(PLAN_ROWS, start=1):
        cells = t.add_row().cells
        cells[0].text = str(idx)
        cells[1].text = title
        week_set = set(weeks)
        for wi in range(15):
            cells[wi + 2].text = "●" if (wi + 1) in week_set else ""


def build_docx() -> Document:
    doc = _setup_doc()
    for block in (SECTION_23, SECTION_24):
        for line in block:
            if not line.strip():
                doc.add_paragraph()
            elif line.startswith("2.3 ") or line.startswith("2.4 "):
                _heading(doc, line)
            else:
                _para(doc, line)
    _add_plan_table(doc)
    return doc


def build_txt() -> str:
    lines = list(SECTION_23) + [""] + list(SECTION_24) + [""]
    lines.append("Таблица 2.2 (● — работа на данной неделе)")
    lines.append("\t".join(["№", "Этап"] + WEEK_DATES))
    for idx, (title, weeks) in enumerate(PLAN_ROWS, start=1):
        week_set = set(weeks)
        row = [str(idx), title] + ["●" if (wi + 1) in week_set else "" for wi in range(15)]
        lines.append("\t".join(row))
    return "\n".join(lines).rstrip() + "\n"


def main() -> None:
    OUT_DOCX.parent.mkdir(parents=True, exist_ok=True)
    OUT_TXT.write_text(build_txt(), encoding="utf-8")
    build_docx().save(OUT_DOCX)
    print(f"OK: {OUT_DOCX}")
    print(f"OK: {OUT_TXT}")
    print(f"Wireframes: {ROOT / 'reports' / 'wireframes'}")


if __name__ == "__main__":
    main()
