def _setup_doc() -> Document:
    doc = Document()
    style = doc.styles["Normal"]
    style.font.name = "Times New Roman"
    style._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    style.font.size = Pt(14)
    return doc


def build_docx() -> Document:
    doc = _setup_doc()
    for line in SECTION_34:
        if not line.strip():
            doc.add_paragraph()
            continue
        if line.startswith("3.4 "):
            p = doc.add_paragraph(line)
            if p.runs:
                p.runs[0].bold = True
            continue
        if line.startswith("Рисунок 3.4"):
            p = doc.add_paragraph(line)
            if p.runs:
                p.runs[0].italic = True
            continue
        doc.add_paragraph(line)
    return doc


def main() -> None:
    OUT_DOCX.parent.mkdir(parents=True, exist_ok=True)
    OUT_TXT.write_text("\n".join(SECTION_34) + "\n", encoding="utf-8")
    build_docx().save(OUT_DOCX)
    print(f"OK: {OUT_DOCX}")
    print(f"OK: {OUT_TXT}")
    if OUT_PUML.exists():
        print(f"OK: {OUT_PUML}")
    else:
        print(f"WARN: {OUT_PUML} not found — create manually or copy from repo")
    print("EA project: reports/uml/fig3_4_database.eapx  (python scripts/generate_eapx_section_34.py)")


if __name__ == "__main__":
    main()
