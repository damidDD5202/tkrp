def _setup_doc() -> Document:
    doc = Document()
    style = doc.styles["Normal"]
    style.font.name = "Times New Roman"
    style._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    style.font.size = Pt(14)
    return doc


def _heading(doc: Document, text: str) -> None:
    p = doc.add_paragraph(text)
    if p.runs:
        p.runs[0].bold = True


def _para(doc: Document, text: str = "") -> None:
    doc.add_paragraph(text)


def _add_table(doc: Document, rows: list[list[str]]) -> None:
    t = doc.add_table(rows=1, cols=len(HEADERS))
    t.style = "Table Grid"
    for i, h in enumerate(HEADERS):
        t.rows[0].cells[i].text = h
        if t.rows[0].cells[i].paragraphs[0].runs:
            t.rows[0].cells[i].paragraphs[0].runs[0].bold = True
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            cells[i].text = val


def build_docx() -> Document:
    doc = _setup_doc()

    _heading(doc, "2 Проектирование программного модуля")
    _heading(doc, "2.1 Перечень функциональности")
    _para(doc, "Таблица 2.1 — Перечень функциональности подсистемы «Отображение свободных и занятых мест»")
    _add_table(doc, TABLE_2_1_PART1)
    _para(doc, "Продолжение таблицы 2.1")
    _add_table(doc, TABLE_2_1_PART2)

    _heading(doc, "2.2 Сценарии взаимодействия")
    _para(doc, SCENARIOS_INTRO)
    for title, steps in SCENARIOS:
        _para(doc, title)
        for step in steps:
            _para(doc, step)

    return doc


def build_txt() -> str:
    lines: list[str] = [
        "2 Проектирование программного модуля",
        "",
        "2.1 Перечень функциональности",
        "",
        "Таблица 2.1 — Перечень функциональности подсистемы «Отображение свободных и занятых мест»",
        "",
        "\t".join(HEADERS),
    ]
    for row in TABLE_2_1_PART1:
        lines.append("\t".join(row))
    lines.extend(["", "Продолжение таблицы 2.1", "", "\t".join(HEADERS)])
    for row in TABLE_2_1_PART2:
        lines.append("\t".join(row))
    lines.extend(["", "2.2 Сценарии взаимодействия", "", SCENARIOS_INTRO, ""])
    for title, steps in SCENARIOS:
        lines.append(title)
        for step in steps:
            lines.append(step)
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main() -> None:
    OUT_DOCX.parent.mkdir(parents=True, exist_ok=True)
    OUT_TXT.write_text(build_txt(), encoding="utf-8")
    build_docx().save(OUT_DOCX)
    print(f"OK: {OUT_DOCX}")
    print(f"OK: {OUT_TXT}")


if __name__ == "__main__":
    main()
